-- VOXRELAY core schema (Postgres / Supabase)
-- Dedicated `voxrelay` schema. No table holds patient/client identity,
-- audio recordings, transcripts, or conversation content.

CREATE SCHEMA IF NOT EXISTS voxrelay;

CREATE TABLE IF NOT EXISTS voxrelay.profiles (
  user_id UUID PRIMARY KEY,
  display_name TEXT NOT NULL DEFAULT '',
  time_zone TEXT NOT NULL DEFAULT 'UTC',
  language_pairs JSONB NOT NULL DEFAULT '[]',
  modalities JSONB NOT NULL DEFAULT '[]',
  weekly_hours INTEGER,
  notifications JSONB NOT NULL DEFAULT '{}',
  retention_days INTEGER,
  locale TEXT NOT NULL DEFAULT 'en',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS voxrelay.availability_overrides (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL,
  date TEXT NOT NULL,
  kind TEXT NOT NULL CHECK (kind IN ('unavailable', 'custom')),
  hours JSONB NOT NULL DEFAULT '[]',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (user_id, date)
);

CREATE TABLE IF NOT EXISTS voxrelay.organizations (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name TEXT NOT NULL,
  created_by UUID NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS voxrelay.memberships (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  org_id UUID NOT NULL REFERENCES voxrelay.organizations(id) ON DELETE CASCADE,
  user_id UUID NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('owner', 'admin', 'coordinator', 'interpreter')),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'removed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (org_id, user_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_voxrelay_membership_one_org
  ON voxrelay.memberships(user_id) WHERE status = 'active';
CREATE INDEX IF NOT EXISTS idx_voxrelay_membership_org
  ON voxrelay.memberships(org_id);

CREATE TABLE IF NOT EXISTS voxrelay.invitations (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  org_id UUID NOT NULL REFERENCES voxrelay.organizations(id) ON DELETE CASCADE,
  email TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('admin', 'coordinator', 'interpreter')),
  token_hash TEXT NOT NULL UNIQUE,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted', 'expired', 'revoked')),
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_voxrelay_invitations_org ON voxrelay.invitations(org_id);

CREATE TABLE IF NOT EXISTS voxrelay.assignments (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  ref TEXT NOT NULL UNIQUE,
  owner_id UUID NOT NULL,
  org_id UUID REFERENCES voxrelay.organizations(id) ON DELETE SET NULL,
  start_at TIMESTAMPTZ,
  duration_minutes INTEGER,
  time_zone TEXT NOT NULL DEFAULT 'UTC',
  language_pair TEXT NOT NULL DEFAULT '',
  modality TEXT NOT NULL DEFAULT '',
  category TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'scheduled' CHECK (status IN (
    'offered', 'scheduled', 'preparation_required', 'ready', 'rescheduled', 'in_progress', 'completed', 'cancelled'
  )),
  offer_state TEXT CHECK (offer_state IN ('pending', 'accepted', 'declined')),
  checklist JSONB NOT NULL DEFAULT '[]',
  personal_note TEXT NOT NULL DEFAULT '',
  exception_category TEXT,
  started_at TIMESTAMPTZ,
  ended_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_voxrelay_assignments_owner ON voxrelay.assignments(owner_id);
CREATE INDEX IF NOT EXISTS idx_voxrelay_assignments_org ON voxrelay.assignments(org_id);
CREATE INDEX IF NOT EXISTS idx_voxrelay_assignments_start ON voxrelay.assignments(start_at);

CREATE TABLE IF NOT EXISTS voxrelay.assignment_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id UUID NOT NULL REFERENCES voxrelay.assignments(id) ON DELETE CASCADE,
  actor_id UUID,
  type TEXT NOT NULL,
  metadata JSONB NOT NULL DEFAULT '{}',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_voxrelay_events_assignment ON voxrelay.assignment_events(assignment_id);

CREATE TABLE IF NOT EXISTS voxrelay.assignment_links (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  assignment_id UUID NOT NULL REFERENCES voxrelay.assignments(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('term', 'resource')),
  ref_id UUID NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS voxrelay.device_checks (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL,
  assignment_id UUID REFERENCES voxrelay.assignments(id) ON DELETE SET NULL,
  result TEXT NOT NULL CHECK (result IN ('pass', 'fail')),
  figures JSONB NOT NULL DEFAULT '{}',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_voxrelay_device_checks_user ON voxrelay.device_checks(user_id);

CREATE TABLE IF NOT EXISTS voxrelay.terms (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  scope TEXT NOT NULL CHECK (scope IN ('personal', 'organization')),
  owner_id UUID,
  org_id UUID REFERENCES voxrelay.organizations(id) ON DELETE CASCADE,
  label TEXT NOT NULL,
  source_lang TEXT NOT NULL DEFAULT '',
  target_lang TEXT NOT NULL DEFAULT '',
  target_term TEXT NOT NULL DEFAULT '',
  notes TEXT NOT NULL DEFAULT '',
  version INTEGER NOT NULL DEFAULT 1,
  approved BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS voxrelay.term_versions (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  term_id UUID NOT NULL REFERENCES voxrelay.terms(id) ON DELETE CASCADE,
  label TEXT NOT NULL,
  version INTEGER NOT NULL,
  snapshot JSONB NOT NULL DEFAULT '{}',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS voxrelay.resources (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  scope TEXT NOT NULL CHECK (scope IN ('personal', 'organization')),
  owner_id UUID,
  org_id UUID REFERENCES voxrelay.organizations(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  url TEXT NOT NULL,
  attribution TEXT NOT NULL DEFAULT '',
  review_date TEXT,
  version INTEGER NOT NULL DEFAULT 1,
  approved BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS voxrelay.saved_resources (
  user_id UUID NOT NULL,
  resource_id UUID NOT NULL REFERENCES voxrelay.resources(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, resource_id)
);

CREATE TABLE IF NOT EXISTS voxrelay.support_requests (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  requester_id UUID NOT NULL,
  org_id UUID REFERENCES voxrelay.organizations(id) ON DELETE SET NULL,
  category TEXT NOT NULL DEFAULT 'general',
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'assigned', 'escalated', 'resolved', 'closed')),
  human_required BOOLEAN NOT NULL DEFAULT false,
  tier TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS voxrelay.support_messages (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  request_id UUID NOT NULL REFERENCES voxrelay.support_requests(id) ON DELETE CASCADE,
  author_id UUID NOT NULL,
  body TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS voxrelay.assistance_policies (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  org_id UUID NOT NULL REFERENCES voxrelay.organizations(id) ON DELETE CASCADE,
  version INTEGER NOT NULL,
  tiers JSONB NOT NULL DEFAULT '{}',
  saved_by UUID NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (org_id, version)
);

CREATE TABLE IF NOT EXISTS voxrelay.audit_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id UUID,
  org_id UUID,
  area TEXT NOT NULL,
  type TEXT NOT NULL,
  object_ref TEXT,
  result TEXT NOT NULL,
  policy_version INTEGER,
  metadata JSONB NOT NULL DEFAULT '{}',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_voxrelay_audit_org ON voxrelay.audit_events(org_id);

CREATE TABLE IF NOT EXISTS voxrelay.consents (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL,
  type TEXT NOT NULL,
  subject TEXT NOT NULL DEFAULT '',
  state TEXT NOT NULL CHECK (state IN ('given', 'withdrawn')),
  policy_version INTEGER,
  withdrawn_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS voxrelay.access_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL DEFAULT '',
  email TEXT NOT NULL,
  audience TEXT NOT NULL DEFAULT 'interpreter',
  organization TEXT NOT NULL DEFAULT '',
  country TEXT NOT NULL DEFAULT '',
  languages TEXT NOT NULL DEFAULT '',
  consent BOOLEAN NOT NULL DEFAULT false,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'redeemed')),
  reviewer_note TEXT NOT NULL DEFAULT '',
  reviewed_by UUID,
  reviewed_at TIMESTAMPTZ,
  invite_token_hash TEXT,
  invite_expires_at TIMESTAMPTZ,
  org_id UUID REFERENCES voxrelay.organizations(id) ON DELETE SET NULL,
  approved_role TEXT NOT NULL DEFAULT 'interpreter' CHECK (approved_role IN ('interpreter', 'admin')),
  message TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS voxrelay.rate_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key_hash TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_voxrelay_rate_key ON voxrelay.rate_events(key_hash, created_at);

CREATE TABLE IF NOT EXISTS voxrelay.session_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignment_id UUID NOT NULL REFERENCES voxrelay.assignments(id) ON DELETE CASCADE,
  actor_id UUID NOT NULL,
  type TEXT NOT NULL,
  at TIMESTAMPTZ NOT NULL DEFAULT now(),
  metadata JSONB NOT NULL DEFAULT '{}'
);
CREATE INDEX IF NOT EXISTS idx_voxrelay_session_events_assignment ON voxrelay.session_events(assignment_id);

CREATE TABLE IF NOT EXISTS voxrelay.session_docs (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  assignment_id UUID NOT NULL UNIQUE REFERENCES voxrelay.assignments(id) ON DELETE CASCADE,
  author_id UUID NOT NULL,
  org_id UUID REFERENCES voxrelay.organizations(id) ON DELETE SET NULL,
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'submitted', 'approved')),
  encounter_type TEXT NOT NULL DEFAULT '',
  mode TEXT NOT NULL DEFAULT '',
  intervention_counts JSONB NOT NULL DEFAULT '{}',
  flags JSONB NOT NULL DEFAULT '[]',
  process_note TEXT NOT NULL DEFAULT '',
  version INTEGER NOT NULL DEFAULT 1,
  submitted_at TIMESTAMPTZ,
  reviewed_by UUID,
  reviewed_at TIMESTAMPTZ,
  review_result TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS voxrelay.followups (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  org_id UUID REFERENCES voxrelay.organizations(id) ON DELETE CASCADE,
  assignment_id UUID REFERENCES voxrelay.assignments(id) ON DELETE SET NULL,
  proposer_id UUID NOT NULL,
  assignee_id UUID,
  type TEXT NOT NULL DEFAULT 'general',
  due_date TEXT,
  status TEXT NOT NULL DEFAULT 'proposed' CHECK (status IN ('proposed', 'approved', 'assigned', 'in_progress', 'completed', 'cancelled')),
  approved_by UUID,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_voxrelay_followups_org ON voxrelay.followups(org_id);

CREATE TABLE IF NOT EXISTS voxrelay.billing_settings (
  user_id UUID PRIMARY KEY,
  rate_cents INTEGER NOT NULL DEFAULT 0,
  currency TEXT NOT NULL DEFAULT 'USD',
  rules JSONB NOT NULL DEFAULT '{}',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS voxrelay.billing_records (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID NOT NULL,
  assignment_ref TEXT,
  minutes INTEGER NOT NULL,
  rate_cents INTEGER NOT NULL,
  currency TEXT NOT NULL DEFAULT 'USD',
  amount_cents INTEGER NOT NULL,
  status TEXT NOT NULL DEFAULT 'invoiced' CHECK (status IN ('invoiced', 'paid')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  paid_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_voxrelay_billing_user ON voxrelay.billing_records(user_id);
